CREATE DATABASE IF NOT EXISTS CONFEITARIA
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE CONFEITARIA;

CREATE TABLE IMAGENS (
  idIMAGENS INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  url_IMAGENS VARCHAR(255) NULL,
  PRIMARY KEY (idIMAGENS)
) ENGINE=InnoDB;

CREATE TABLE CLIENTES (
  idCLIENTES INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  nome_Clientes VARCHAR(50) NOT NULL,
  endereco_Clientes VARCHAR(45) NULL,
  telefone_Clientes VARCHAR(11) NULL,
  senha_Clientes VARCHAR(255) NOT NULL,
  PRIMARY KEY (idCLIENTES)
) ENGINE=InnoDB;

CREATE TABLE ADMINISTRADOR (
  idADMINISTRADOR INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  nome_ADMINISTRADOR VARCHAR(20) NULL,
  email_ADMINISTRADOR VARCHAR(25) NULL,
  senha_ADMINISTRADOR VARCHAR(255) NULL,
  PRIMARY KEY (idADMINISTRADOR)
) ENGINE=InnoDB;

CREATE TABLE PEDIDOS (
  idPEDIDOS INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  CLIENTES_idCLIENTES INTEGER UNSIGNED NOT NULL,
  data_PEDIDOS VARCHAR(11) NULL,
  status_PEDIDOS VARCHAR(20) NULL,
  retirada_PEDIDOS VARCHAR(45) NULL,
  PRIMARY KEY (idPEDIDOS, CLIENTES_idCLIENTES),
  INDEX PEDIDOS_FKIndex2 (CLIENTES_idCLIENTES),
  FOREIGN KEY (CLIENTES_idCLIENTES)
    REFERENCES CLIENTES (idCLIENTES)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
) ENGINE=InnoDB;

CREATE TABLE PRODUTOS (
  idPRODUTOS INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  IMAGENS_idIMAGENS INTEGER UNSIGNED NOT NULL,
  nome_PRODUTOS VARCHAR(100) NULL,
  descricao_PRODUTOS VARCHAR(255) NULL,
  preco_PRODUTOS INTEGER UNSIGNED NULL,
  status_PRODUTOS VARCHAR(13) NULL,
  foto_PRODUTOS VARCHAR(255) NULL,
  PRIMARY KEY (idPRODUTOS),
  INDEX PRODUTOS_FKIndex1 (IMAGENS_idIMAGENS),
  FOREIGN KEY (IMAGENS_idIMAGENS)
    REFERENCES IMAGENS (idIMAGENS)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
) ENGINE=InnoDB;

CREATE TABLE ITENS_PEDIDOS (
  PEDIDOS_idPEDIDOS INTEGER UNSIGNED NOT NULL,
  PRODUTOS_idPRODUTOS INTEGER UNSIGNED NOT NULL,
  PEDIDOS_CLIENTES_idCLIENTES INTEGER UNSIGNED NOT NULL,
  quantidade_PRODUTOS INTEGER UNSIGNED NULL,
  PRIMARY KEY (PEDIDOS_idPEDIDOS, PRODUTOS_idPRODUTOS, PEDIDOS_CLIENTES_idCLIENTES),
  INDEX PEDIDOS_has_PRODUTOS_FKIndex1 (PEDIDOS_idPEDIDOS, PEDIDOS_CLIENTES_idCLIENTES),
  INDEX PEDIDOS_has_PRODUTOS_FKIndex2 (PRODUTOS_idPRODUTOS),
  FOREIGN KEY (PEDIDOS_idPEDIDOS, PEDIDOS_CLIENTES_idCLIENTES)
    REFERENCES PEDIDOS (idPEDIDOS, CLIENTES_idCLIENTES)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION,
  FOREIGN KEY (PRODUTOS_idPRODUTOS)
    REFERENCES PRODUTOS (idPRODUTOS)
    ON DELETE NO ACTION
    ON UPDATE NO ACTION
) ENGINE=InnoDB;

CREATE TABLE AVALIACOES (
  idAVALIACOES INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
  ITENS_PEDIDOS_PEDIDOS_idPEDIDOS INTEGER UNSIGNED NOT NULL,
  ITENS_PEDIDOS_PEDIDOS_CLIENTES_idCLIENTES INTEGER UNSIGNED NOT NULL,
  ITENS_PEDIDOS_PRODUTOS_idPRODUTOS INTEGER UNSIGNED NOT NULL,
  nota_AVALIACOES TINYINT UNSIGNED NOT NULL,
  comentario_AVALIACOES VARCHAR(255) NULL,
  data_AVALIACOES DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (idAVALIACOES),
  UNIQUE KEY uq_avaliacao_item (
    ITENS_PEDIDOS_PEDIDOS_idPEDIDOS,
    ITENS_PEDIDOS_PEDIDOS_CLIENTES_idCLIENTES,
    ITENS_PEDIDOS_PRODUTOS_idPRODUTOS
  ),
  CONSTRAINT chk_nota_AVALIACOES CHECK (nota_AVALIACOES BETWEEN 1 AND 5),
  FOREIGN KEY (
    ITENS_PEDIDOS_PEDIDOS_idPEDIDOS,
    ITENS_PEDIDOS_PRODUTOS_idPRODUTOS,
    ITENS_PEDIDOS_PEDIDOS_CLIENTES_idCLIENTES
  )
    REFERENCES ITENS_PEDIDOS (
      PEDIDOS_idPEDIDOS,
      PRODUTOS_idPRODUTOS,
      PEDIDOS_CLIENTES_idCLIENTES
    )
    ON DELETE CASCADE
    ON UPDATE NO ACTION
) ENGINE=InnoDB;


